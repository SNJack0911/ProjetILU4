    public void ajouterJCarte(JCarte jCarte){
        GridBagConstraints gbc = new GridBagConstraints();
        gbc.insets = new Insets(10, 10, 10, 10);
        gbc.gridy = 0;
        gbc.gridx = mainJoueur.size();
        mainJoueur.add(jCarte);
        this.add(jCarte, gbc);
        this.revalidate();
        this.repaint();
    }
    
    public List<JCarte> getMainJoueur() {
        return mainJoueur;
    }
    
